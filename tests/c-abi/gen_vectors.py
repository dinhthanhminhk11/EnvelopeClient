"""Writes vectors.h for the C ABI smoke tests (tools/c-abi-smoke.sh) from the vectors of the server
(server/src/core/envelope/testdata: envelope-v1.json and app-attest-v1.json).

    python3 -I gen_vectors.py <server/src/core/envelope/testdata dir> <output vectors.h>

String macros (case 0 of each group) are what the Swift smoke test sees through its bridging header; the C smoke test
also walks every case through the arrays. Byte values are lowercase hex, text is the vector's exact UTF-8.
"""

import base64
import hashlib
import json
import sys


def c_string(value):
    out = '"'
    for byte in value.encode("utf-8"):
        char = chr(byte)
        if char in '"\\' or byte < 0x20 or byte > 0x7E or char == "?":
            out += "\\%03o" % byte
        else:
            out += char
    return out + '"'


def main(testdata, output):
    with open(testdata + "/envelope-v1.json", encoding="utf-8") as handle:
        envelope = json.load(handle)
    with open(testdata + "/app-attest-v1.json", encoding="utf-8") as handle:
        attest = json.load(handle)

    lines = ["/* Generated by tests/c-abi/gen_vectors.py from server/src/core/envelope/testdata; do not edit. */"]
    lines += ["#ifndef DOODLEART_VECTORS_H", "#define DOODLEART_VECTORS_H", ""]
    define = lambda name, value: lines.append("#define %s %s" % (name, c_string(value)))

    define("V_SPKI_HEX", envelope["device_spki"])
    define("V_DEVICE_KEY_ID", envelope["key_id"])
    define("V_DAAS1_MESSAGE_HEX", attest["start_message"])
    define("V_DAAS1_HASH_HEX", attest["session_assert_client_data_hash"])
    device = attest["ios_device_hash"]
    define("V_IOS_SECRET_HEX", device[0]["secret"])
    define("V_IOS_HASH", device[0]["hash"])

    # doodleart_register_message: nonce text (base64url of the 24 vector bytes), device_id, device_key_id, platform.
    nonce = base64.urlsafe_b64encode(bytes.fromhex(envelope["nonce"])).decode().rstrip("=")
    for index, value in enumerate([nonce, envelope["device_id"], envelope["key_id"], envelope["platform"]]):
        define("V_REG_%d" % index, value)
    define("V_REG_MESSAGE_HEX", attest["register_message"])
    define("V_REG_HASH_HEX", attest["register_client_data_hash"])

    def dapi1_row(case):
        return [case["method"], case["path_with_query"], case["request_id"], case["sid"],
                case["body"].encode("utf-8").hex(), case["request_hash_b64"], case["request_hash"]]

    rows = [dapi1_row(case) for case in attest["integrity"]]
    for index, value in enumerate(rows[1]):
        define("V_DAPI1_%d" % index, value)

    lines += ["", "#ifndef __swift__", "#define V_IOS_COUNT %d" % len(device), "static const char *const V_IOS[][2] = {"]
    for case in device:
        lines.append("    {%s, %s}," % (c_string(case["secret"]), c_string(case["hash"])))
    lines += ["};", "/* method, pathWithQuery, requestId, sid, bodyHex, requestHash, SHA-256(preimage) hex */"]
    lines += ["#define V_DAPI1_COUNT %d" % len(rows), "static const char *const V_DAPI1[][7] = {"]
    for row in rows:
        lines.append("    {" + ", ".join(c_string(value) for value in row) + "},")
    lines += ["};", "#endif", "", "#endif", ""]

    with open(output, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
