        let entries = crate::risk::maps::parse(&text);
        let first_base_apk = entries.iter().map(|entry| entry.path).find(|path| path.ends_with("/base.apk")).unwrap();
        assert!(first_base_apk.contains("com.google.android.trichromelibrary"), "fixture: a Google APK comes first");

