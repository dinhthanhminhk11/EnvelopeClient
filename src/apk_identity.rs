//! Signing identity of the installed APK, read without PackageManager (which hooks can fake): find our own install
//! directory from the /proc/self/maps entry that backs this library's code, parse `<dir>/base.apk`'s APK Signing Block
//! (v2 / v3 / v3.1) and compare the SHA-256 of every signer's certificate with the allowlist compiled in for the build
//! type. A mismatch is the `apk_resigned` risk flag.
//!
//! The platform verified these signatures at install time; we only read which certificates they are. Every signer of
//! every scheme present must be allowlisted, so an attacker cannot keep a copied block with our certificate next to
//! the scheme the platform actually verifies with theirs.
//!
//! Once the file is readable, anything AGP, apksigner and Play never produce counts as re-signed: no End Of Central
//! Directory, ZIP64, bytes between the central directory and the EOCD, a malformed or oversized signing block, a
//! v2/v3/v3.1 pair that does not parse, the same scheme twice. The platform reads only the first pair per scheme and
//! puts no limit on the block size, so treating those as "unknown" would let a crafted block hide the real signer.
//! Only I/O failures (file missing or unreadable) give `Unknown`.

use sha2::{Digest, Sha256};

use crate::sys;

const EOCD_SIGNATURE: u32 = 0x0605_4b50;
const EOCD_SIZE: usize = 22;
const MAX_COMMENT: usize = 0xffff;
const CD_ENTRY_SIGNATURE: u32 = 0x0201_4b50;
const LOCAL_HEADER_SIGNATURE: u32 = 0x0403_4b50;
const MAX_SIGNING_BLOCK: u64 = 16 * 1024 * 1024;
const MAX_CENTRAL_DIRECTORY: u64 = 32 * 1024 * 1024;

pub const SCHEME_V2: u32 = 0x7109_871a;
pub const SCHEME_V3: u32 = 0xf053_68c0;
pub const SCHEME_V31: u32 = 0x1b93_ad61;

/// Allowlist per build type (theme-x plan §1.3, §7.4). Not settable from Kotlin. The digests are per project (theme-x spec 2026-11-05
/// D-P4-4) and generated by build.rs: release and QA from the project config (`config/project.conf` or
/// `DOODLEART_PROJECT_CONF`, keys `RELEASE_APK_CERT_SHA256` / `QA_APK_CERT_SHA256`; a release or QA build without a digest
/// of its type stops), debug from `config/debug-certs.conf` (debug keystores differ per machine).
///
/// `android_guard_tests` pins the DoodleArt values to the former constants of this file: the app signing key (Google Play
/// App Signing, C2:4A:2C:20:…:2D:C7) for release, the upload key (alias doodleart, F3:BA:AC:09:…:88:37) for QA.
#[cfg(feature = "build-release")]
pub const ALLOWED_CERT_SHA256: &[[u8; 32]] = crate::build_config::RELEASE_APK_CERT_SHA256;
#[cfg(feature = "build-qa")]
pub const ALLOWED_CERT_SHA256: &[[u8; 32]] = crate::build_config::QA_APK_CERT_SHA256;
#[cfg(feature = "build-debug")]
pub const ALLOWED_CERT_SHA256: &[[u8; 32]] = crate::build_config::DEBUG_CERT_SHA256;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ApkVerdict {
    /// Every signer certificate is in the allowlist.
    Allowed,
    /// A signer certificate is not allowed, the APK has no v2/v3 signature, or its layout is one no legitimate signer
    /// produces: `apk_resigned`.
    Resigned,
    /// The APK could not be located, opened or read: no verdict, no flag.
    Unknown,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ApkError {
    /// The file could not be read. The only error without a verdict.
    Io,
    /// No End Of Central Directory record.
    NotZip,
    /// A layout legitimate signers never produce (see the module documentation).
    Malformed,
    /// Valid ZIP without an APK Signing Block, or a block without v2/v3/v3.1 signers.
    NoSignature,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SignerCerts {
    /// Schemes present, in block order.
    pub schemes: Vec<u32>,
    /// SHA-256 of the first certificate of each signer, deduplicated.
    pub cert_sha256: Vec<[u8; 32]>,
}

/// Random access reads: the installed APK (raw syscalls) or a byte slice in tests.
pub trait ReadAt {
    fn size(&self) -> u64;
    fn read_at(&self, out: &mut [u8], offset: u64) -> bool;
}

impl ReadAt for [u8] {
    fn size(&self) -> u64 {
        self.len() as u64
    }

    fn read_at(&self, out: &mut [u8], offset: u64) -> bool {
        let Ok(start) = usize::try_from(offset) else { return false };
        match self.get(start..start.saturating_add(out.len())) {
            Some(bytes) if bytes.len() == out.len() => {
                out.copy_from_slice(bytes);
                true
            }
            _ => false,
        }
    }
}

/// An open file read with pread64 through raw syscalls.
pub struct FileReader {
    fd: sys::Fd,
    size: u64,
}

impl FileReader {
    pub fn open(path: &str) -> Option<Self> {
        let fd = sys::open(path)?;
        let size = file_size(&fd)?;
        Some(Self { fd, size })
    }
}

/// Size by probing with pread: avoids fstat structure layouts that differ per ABI.
fn file_size(fd: &sys::Fd) -> Option<u64> {
    let mut byte = [0u8; 1];
    if fd.pread(&mut byte, 0)? == 0 {
        return Some(0);
    }
    let (mut low, mut high) = (0u64, 1u64);
    while fd.pread(&mut byte, high)? == 1 {
        low = high;
        high = high.checked_mul(2)?;
        if high > 1 << 40 {
            return None;
        }
    }
    // Invariant: byte at `low` exists, byte at `high` does not.
    while high - low > 1 {
        let middle = low + (high - low) / 2;
        if fd.pread(&mut byte, middle)? == 1 {
            low = middle;
        } else {
            high = middle;
        }
    }
    Some(high)
}

impl ReadAt for FileReader {
    fn size(&self) -> u64 {
        self.size
    }

    fn read_at(&self, out: &mut [u8], offset: u64) -> bool {
        sys::pread_exact(&self.fd, out, offset)
    }
}

/// `length` bytes at `offset`. A range outside the file comes from a bad length or offset field (`Malformed`); only a
/// failed read of an existing range is `Io`.
fn read_vec<R: ReadAt + ?Sized>(reader: &R, offset: u64, length: u64) -> Result<Vec<u8>, ApkError> {
    if offset.checked_add(length).is_none_or(|end| end > reader.size()) {
        return Err(ApkError::Malformed);
    }
    let length = usize::try_from(length).map_err(|_| ApkError::Malformed)?;
    let mut out = vec![0u8; length];
    if reader.read_at(&mut out, offset) {
        Ok(out)
    } else {
        Err(ApkError::Io)
    }
}

fn u16_le(bytes: &[u8], at: usize) -> Option<u16> {
    Some(u16::from_le_bytes(bytes.get(at..at + 2)?.try_into().ok()?))
}

fn u32_le(bytes: &[u8], at: usize) -> Option<u32> {
    Some(u32::from_le_bytes(bytes.get(at..at + 4)?.try_into().ok()?))
}

fn u64_le(bytes: &[u8], at: usize) -> Option<u64> {
    Some(u64::from_le_bytes(bytes.get(at..at + 8)?.try_into().ok()?))
}

/// Location of the central directory, from the End Of Central Directory record.
#[derive(Clone, Copy, Debug)]
pub(crate) struct ZipLayout {
    pub cd_offset: u64,
    pub cd_size: u64,
}

pub(crate) fn zip_layout<R: ReadAt + ?Sized>(reader: &R) -> Result<ZipLayout, ApkError> {
    let size = reader.size();
    if size < EOCD_SIZE as u64 {
        return Err(ApkError::NotZip);
    }
    let tail_length = size.min((EOCD_SIZE + MAX_COMMENT) as u64);
    let tail = read_vec(reader, size - tail_length, tail_length)?;
    // Scan backwards; the comment length must reach exactly the end of the file.
    let eocd = (0..=tail.len() - EOCD_SIZE).rev().find(|&at| {
        u32_le(&tail, at) == Some(EOCD_SIGNATURE)
            && u16_le(&tail, at + 20).is_some_and(|comment| at + EOCD_SIZE + usize::from(comment) == tail.len())
    });
    let at = eocd.ok_or(ApkError::NotZip)?;
    let cd_size = u64::from(u32_le(&tail, at + 12).ok_or(ApkError::NotZip)?);
    let cd_offset = u64::from(u32_le(&tail, at + 16).ok_or(ApkError::NotZip)?);
    let eocd_offset = size - tail_length + at as u64;
    // ZIP64 markers or a central directory not directly before the EOCD: not an APK layout we read.
    if cd_offset == 0xffff_ffff || cd_offset.checked_add(cd_size) != Some(eocd_offset) {
        return Err(ApkError::Malformed);
    }
    Ok(ZipLayout { cd_offset, cd_size })
}

/// The APK Signing Block's ID-value pairs region, or `NoSignature` when the ZIP has none.
fn signing_block<R: ReadAt + ?Sized>(reader: &R, layout: ZipLayout) -> Result<Vec<u8>, ApkError> {
    if layout.cd_offset < 32 {
        return Err(ApkError::NoSignature);
    }
    let footer = read_vec(reader, layout.cd_offset - 24, 24)?;
    if footer[8..24] != *obfstr::obfbytes!(b"APK Sig Block 42") {
        return Err(ApkError::NoSignature);
    }
    let block_size = u64_le(&footer, 0).ok_or(ApkError::Malformed)?;
    if !(24..=MAX_SIGNING_BLOCK).contains(&block_size) || block_size + 8 > layout.cd_offset {
        return Err(ApkError::Malformed);
    }
    let start = layout.cd_offset - block_size - 8;
    let block = read_vec(reader, start, block_size + 8)?;
    if u64_le(&block, 0) != Some(block_size) {
        return Err(ApkError::Malformed);
    }
    Ok(block[8..block.len() - 24].to_vec())
}

/// Reads a u32-length-prefixed slice and advances `input`.
fn take_prefixed<'a>(input: &mut &'a [u8]) -> Option<&'a [u8]> {
    let length = u32_le(input, 0)? as usize;
    let rest = input.get(4..)?;
    if rest.len() < length {
        return None;
    }
    let (value, tail) = rest.split_at(length);
    *input = tail;
    Some(value)
}

/// First certificate of each signer in a v2 / v3 / v3.1 scheme block.
fn signer_first_certs(scheme: u32, value: &[u8]) -> Option<Vec<[u8; 32]>> {
    let mut value = value;
    let mut signers = take_prefixed(&mut value)?;
    let mut out = Vec::new();
    while !signers.is_empty() {
        let mut signer = take_prefixed(&mut signers)?;
        let mut signed_data = take_prefixed(&mut signer)?;
        let _digests = take_prefixed(&mut signed_data)?;
        let mut certificates = take_prefixed(&mut signed_data)?;
        let first = take_prefixed(&mut certificates)?;
        if first.is_empty() {
            return None;
        }
        // v3 / v3.1 signers carry minSdk / maxSdk after signed_data; the certificates are what we compare.
        if scheme != SCHEME_V2 && signer.len() < 8 {
            return None;
        }
        out.push(Sha256::digest(first).into());
    }
    (!out.is_empty()).then_some(out)
}

/// Signer certificates of an APK.
pub fn signer_certs<R: ReadAt + ?Sized>(reader: &R) -> Result<SignerCerts, ApkError> {
    let layout = zip_layout(reader)?;
    let pairs = signing_block(reader, layout)?;
    let mut rest = pairs.as_slice();
    let mut schemes: Vec<u32> = Vec::new();
    let mut digests: Vec<[u8; 32]> = Vec::new();
    while !rest.is_empty() {
        let length = u64_le(rest, 0).ok_or(ApkError::Malformed)?;
        let body = rest.get(8..).ok_or(ApkError::Malformed)?;
        if length < 4 || length > body.len() as u64 {
            return Err(ApkError::Malformed);
        }
        let (pair, tail) = body.split_at(length as usize);
        rest = tail;
        let id = u32_le(pair, 0).ok_or(ApkError::Malformed)?;
        if matches!(id, SCHEME_V2 | SCHEME_V3 | SCHEME_V31) {
            // The platform only reads the first pair of each scheme; a second one exists to hide something.
            if schemes.contains(&id) {
                return Err(ApkError::Malformed);
            }
            let certs = signer_first_certs(id, &pair[4..]).ok_or(ApkError::Malformed)?;
            schemes.push(id);
            for digest in certs {
                if !digests.contains(&digest) {
                    digests.push(digest);
                }
            }
        }
    }
    if schemes.is_empty() {
        return Err(ApkError::NoSignature);
    }
    Ok(SignerCerts { schemes, cert_sha256: digests })
}

pub fn verdict(result: &Result<SignerCerts, ApkError>, allowlist: &[[u8; 32]]) -> ApkVerdict {
    match result {
        Ok(certs) if !certs.cert_sha256.is_empty() && certs.cert_sha256.iter().all(|d| allowlist.contains(d)) => {
            ApkVerdict::Allowed
        }
        Err(ApkError::Io) => ApkVerdict::Unknown,
        Ok(_) | Err(ApkError::NotZip | ApkError::Malformed | ApkError::NoSignature) => ApkVerdict::Resigned,
    }
}

/// `<dir>/base.apk` of the package whose code is mapped from `own_code_path` (the /proc/self/maps path of the
/// mapping that holds this library's code), or `None` when that path is not inside an installed package:
/// - `<dir>/base.apk` or `<dir>/split_config.<abi>.apk`: the library is loaded straight from the APK;
/// - `<dir>/lib/<isa>/<name>.so`: the library was extracted at install time.
///
/// Never "the first base.apk in maps": WebView / Trichrome / GMS map their own `/data/app/…/base.apk` into every app
/// that shows an ad, often at lower addresses than ours, and those are signed by Google.
pub fn own_base_apk(own_code_path: &str) -> Option<String> {
    let (dir, file) = own_code_path.rsplit_once('/')?;
    let install_dir = if file.ends_with(".apk") {
        dir
    } else if file.ends_with(".so") {
        let (lib_dir, isa) = dir.rsplit_once('/')?;
        if isa.is_empty() {
            return None;
        }
        lib_dir.strip_suffix("/lib")?
    } else {
        return None;
    };
    is_package_dir(install_dir).then(|| format!("{install_dir}/base.apk"))
}

/// A package directory under /data/app (or /mnt/expand/<uuid>/app on adopted storage): at least one component below
/// the app root, no empty, `.` or `..` component.
fn is_package_dir(dir: &str) -> bool {
    let below_root = match dir.strip_prefix("/data/app/") {
        Some(rest) => Some(rest),
        None => dir.strip_prefix("/mnt/expand/").and_then(|rest| rest.split_once("/app/")).map(|(_, rest)| rest),
    };
    below_root.is_some_and(|rest| !rest.is_empty() && rest.split('/').all(|part| !matches!(part, "" | "." | "..")))
}

/// Verdict for the APK at `path` (from [`own_base_apk`]).
pub fn check_file(path: &str) -> ApkVerdict {
    let Some(reader) = FileReader::open(path) else { return ApkVerdict::Unknown };
    verdict(&signer_certs(&reader), ALLOWED_CERT_SHA256)
}

/// Data offset of the STORED (uncompressed) entry whose data holds `file_offset`: the ELF image of a library the
/// linker maps straight from an APK (`extractNativeLibs=false`), located from the mapping's file offset alone.
pub(crate) fn stored_entry_containing<R: ReadAt + ?Sized>(reader: &R, file_offset: u64) -> Option<u64> {
    let layout = zip_layout(reader).ok()?;
    if layout.cd_size > MAX_CENTRAL_DIRECTORY {
        return None;
    }
    let cd = read_vec(reader, layout.cd_offset, layout.cd_size).ok()?;
    // The stored entry with the highest local header offset still below `file_offset`.
    let mut best: Option<(u64, u64)> = None;
    let mut at = 0usize;
    while at + 46 <= cd.len() {
        if u32_le(&cd, at)? != CD_ENTRY_SIGNATURE {
            return None;
        }
        let method = u16_le(&cd, at + 10)?;
        let compressed_size = u64::from(u32_le(&cd, at + 20)?);
        let name_length = usize::from(u16_le(&cd, at + 28)?);
        let extra_length = usize::from(u16_le(&cd, at + 30)?);
        let comment_length = usize::from(u16_le(&cd, at + 32)?);
        let local_offset = u64::from(u32_le(&cd, at + 42)?);
        if method == 0 && local_offset < file_offset && best.is_none_or(|(offset, _)| local_offset > offset) {
            best = Some((local_offset, compressed_size));
        }
        at += 46 + name_length + extra_length + comment_length;
    }
    let (local_offset, size) = best?;
    let local = read_vec(reader, local_offset, 30).ok()?;
    if u32_le(&local, 0)? != LOCAL_HEADER_SIGNATURE {
        return None;
    }
    let data = local_offset.checked_add(30 + u64::from(u16_le(&local, 26)?) + u64::from(u16_le(&local, 28)?))?;
    (data <= file_offset && file_offset - data < size).then_some(data)
}

#[cfg(test)]
const fn hex32(text: &str) -> [u8; 32] {
    const fn nibble(c: u8) -> u8 {
        match c {
            b'0'..=b'9' => c - b'0',
            b'a'..=b'f' => c - b'a' + 10,
            _ => panic!("lowercase hex expected"),
        }
    }
    let bytes = text.as_bytes();
    assert!(bytes.len() == 64);
    let mut out = [0u8; 32];
    let mut index = 0;
    while index < 32 {
        out[index] = nibble(bytes[index * 2]) << 4 | nibble(bytes[index * 2 + 1]);
        index += 1;
    }
    out
}

