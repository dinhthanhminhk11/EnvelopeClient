    /// One ID-value pair of an APK Signing Block.
    fn pair(id: u32, value: &[u8]) -> Vec<u8> {
        let mut out = ((value.len() + 4) as u64).to_le_bytes().to_vec();
        out.extend(id.to_le_bytes());
        out.extend(value);
        out
    }

    /// `apk` with the pairs region of its signing block replaced by `pairs`; the EOCD's central directory offset is
    /// moved accordingly (v2/v3 digests treat that field as pointing at the block, so signatures stay valid).
    fn with_pairs(apk: &[u8], pairs: &[u8]) -> Vec<u8> {
        let layout = zip_layout(apk).unwrap();
        let cd = layout.cd_offset as usize;
        let old_size = u64_le(apk, cd - 24).unwrap() as usize;
        let size = (pairs.len() + 8 + 16) as u64;
        let mut out = apk[..cd - old_size - 8].to_vec();
        out.extend(size.to_le_bytes());
        out.extend(pairs);
        out.extend(size.to_le_bytes());
        out.extend(b"APK Sig Block 42");
        let new_cd = out.len() as u32;
        out.extend(&apk[cd..]);
        let eocd = out.len() - EOCD_SIZE;
        assert_eq!(u32_le(&out, eocd), Some(EOCD_SIGNATURE), "fixture APKs have no ZIP comment");
        out[eocd + 16..eocd + 20].copy_from_slice(&new_cd.to_le_bytes());
        out
    }

    /// apksigner from the newest build-tools that has it, as the platform's stand-in.
    fn apksigner() -> Option<std::path::PathBuf> {
        let sdk = std::env::var("ANDROID_HOME")
            .unwrap_or_else(|_| format!("{}/Library/Android/sdk", std::env::var("HOME").unwrap_or_default()));
        let mut found: Vec<std::path::PathBuf> = std::fs::read_dir(format!("{sdk}/build-tools"))
            .map(|dir| {
                dir.filter_map(|entry| entry.ok())
                    .map(|entry| entry.path().join("apksigner"))
                    .filter(|path| path.exists())
                    .collect()
            })
            .unwrap_or_default();
        found.sort();
        found.pop()
    }

    /// `apksigner verify --min-sdk-version 24` accepts `apk` (what a device would install). `None` without apksigner.
    fn platform_accepts(apk: &[u8], name: &str) -> Option<bool> {
        let apksigner = apksigner()?;
        let path = std::env::temp_dir().join(format!("doodleart-core-{}-{name}.apk", std::process::id()));
        std::fs::write(&path, apk).unwrap();
        let output =
            std::process::Command::new(apksigner).args(["verify", "--min-sdk-version", "24"]).arg(&path).output().ok();
        let _ = std::fs::remove_file(&path);
        output.map(|output| output.status.success())
    }

    /// Re-signed APKs whose block the platform still accepts but a lenient parser would give up on: a second v2 pair
    /// with garbage (the platform reads the first one only) and a 17 MB padding pair (no size limit on device).
    #[test]
    fn crafted_signing_blocks_are_resigned() {
        let foreign = fixture("foreign-v2v3.apk");
        let pairs = signing_block(foreign.as_slice(), zip_layout(foreign.as_slice()).unwrap()).unwrap();
        let allowlist = [hex32(DEBUG_CERT), hex32(UPLOAD_CERT), hex32(APP_SIGNING_CERT)];

        let mut second_v2 = pairs.clone();
        second_v2.extend(pair(SCHEME_V2, &[0x5a; 64]));
        let mut oversized = pairs.clone();
        oversized.extend(pair(0x4272_6577, &vec![0; 17 * 1024 * 1024]));

        let crafted = [("second-v2", with_pairs(&foreign, &second_v2)), ("padding", with_pairs(&foreign, &oversized))];
        for (name, apk) in &crafted {
            assert_eq!(signer_certs(apk.as_slice()), Err(ApkError::Malformed), "{name}");
            assert_eq!(verdict(&signer_certs(apk.as_slice()), &allowlist), ApkVerdict::Resigned, "{name}");
            if let Some(accepted) = platform_accepts(apk, name) {
                assert!(accepted, "{name}: apksigner should still verify the crafted APK");
            }
        }
        // Rebuilding with the original pairs is a no-op, and the oracle does reject a broken signature.
        assert_eq!(with_pairs(&foreign, &pairs), foreign);
        let mut tampered = foreign.clone();
        // One byte of the stored libprobe.so, which the v2/v3 digests cover.
        let content = tampered.windows(7).position(|window| window == b"\x7fELF\x02\x01\x01").unwrap();
        tampered[content + 8] ^= 1;
        assert_ne!(platform_accepts(&tampered, "tampered"), Some(true), "apksigner must refuse a modified entry");
    }

    /// ZIP layouts outside what AGP / apksigner write: bytes between the central directory and the EOCD (a v1-only
    /// APK can still install that way on old targetSdk), and ZIP64 markers.
    #[test]
    fn unusual_zip_layouts_are_resigned() {
        let apk = fixture("debug-v1only.apk");
        let eocd = apk.len() - EOCD_SIZE;
        let mut gap = apk[..eocd].to_vec();
        gap.extend([0u8; 16]);
        gap.extend(&apk[eocd..]);
        assert_eq!(signer_certs(gap.as_slice()), Err(ApkError::Malformed));
        assert_eq!(verdict(&signer_certs(gap.as_slice()), &[hex32(DEBUG_CERT)]), ApkVerdict::Resigned);

        let mut zip64 = fixture("debug-v2v3.apk");
        let eocd = zip64.len() - EOCD_SIZE;
        zip64[eocd + 16..eocd + 20].copy_from_slice(&u32::MAX.to_le_bytes());
        assert_eq!(verdict(&signer_certs(zip64.as_slice()), &[hex32(DEBUG_CERT)]), ApkVerdict::Resigned);
    }

    #[test]
    fn stored_entry_lookup() {
        let apk = fixture("debug-v2v3.apk");
        let elf = apk.windows(7).position(|window| window == b"\x7fELF\x02\x01\x01").unwrap() as u64;
        assert_eq!(stored_entry_containing(apk.as_slice(), elf), Some(elf));
        assert_eq!(stored_entry_containing(apk.as_slice(), elf + 63), Some(elf));
        assert_eq!(stored_entry_containing(apk.as_slice(), elf + 64), None, "past the 64-byte entry");
        let layout = zip_layout(apk.as_slice()).unwrap();
        assert_eq!(stored_entry_containing(apk.as_slice(), layout.cd_offset + 4), None, "central directory");
        assert_eq!(stored_entry_containing(apk.as_slice(), 0), None);
    }

    /// The APK is the one that holds our own code, even when WebView / Trichrome / GMS APKs come first in maps.
