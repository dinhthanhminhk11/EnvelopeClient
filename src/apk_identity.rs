    /// Real APKs built by Gradle in this repo (gitignored, checked when present), with build-tools `apksigner` as the
    /// oracle: our parser must report exactly the signer certificates apksigner prints.
    #[test]
    fn gradle_built_apks_match_apksigner() {
        let Some(apksigner) = apksigner() else { return };
        let root = concat!(env!("CARGO_MANIFEST_DIR"), "/..");
        for path in [
            "app/build/intermediates/apk/production/debug/app-production-debug.apk",
            "app/build/intermediates/apk/staging/debug/app-staging-debug.apk",
            "app/release/app-release.apk",
        ] {
            let full = format!("{root}/{path}");
            let Some(reader) = FileReader::open(&full) else { continue };
            let output =
                std::process::Command::new(&apksigner).args(["verify", "--print-certs", &full]).output().unwrap();
            let mut expected: Vec<String> = String::from_utf8_lossy(&output.stdout)
                .lines()
                .filter(|line| line.contains("certificate SHA-256 digest:"))
                .filter_map(|line| line.rsplit(' ').next().map(str::to_owned))
                .collect();
            let result = signer_certs(&reader);
            // Real AGP output never trips the "layout no legitimate signer produces" rules.
            assert!(result.is_ok(), "{path}: {result:?}");
            let mut ours = digests(&result.unwrap());
            expected.sort();
            ours.sort();
            assert_eq!(ours, expected, "{path}");
        }
    }
