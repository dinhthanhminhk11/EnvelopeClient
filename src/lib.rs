// build.rs sets `doodleart_apple_lib` exactly for Apple libraries: never elsewhere, always for iOS and the other
// Apple OSes.
#[cfg(all(doodleart_apple_lib, not(target_vendor = "apple")))]
compile_error!("doodleart_apple_lib is set for a non-Apple target");
#[cfg(all(target_vendor = "apple", not(target_os = "macos"), not(doodleart_apple_lib)))]
compile_error!("an Apple library without doodleart_apple_lib: the Android parts would be compiled into it");

