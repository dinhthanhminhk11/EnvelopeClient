//! doodleart-core: the native security core of the DoodleArt apps, ported from the Rust core of theme-x. One crate for
//! iOS (C ABI, `DoodleArtCore.xcframework`) and Android (JNI), speaking the secure session protocol of the app service
//! (server/docs/app-security.md; byte layouts in server/src/core/envelope, vectors in its testdata/).
//!
//! - [`envelope`]: client side of envelope v1 (registration message, handshake, sealed requests and responses).
//! - [`integrity_hash`]: registration proof, App Attest assertion of a handshake (DAAS1), protected request hash
//!   (DAPI1), `iosDeviceHash`.
//! - `device_signals`: `androidIdHash`, `drmIdHash`, `hwFpHash` (CNHW1).
//! - [`risk`]: Frida / hook / root / emulator / debugger detection, reported as flags, never acted on locally.
//! - `apk_identity`: signing certificates of the installed APK from its APK Signing Block.
//! - `jni`: `JNI_OnLoad` + `RegisterNatives` for `com.cem.doodleart.security.NativeCore`; the only exported symbol of
//!   the Android library.
//! - `ffi`: the C ABI of the iOS app (`doodleart_*`, include/doodleart_core.h), Apple libraries only.
//!
//! Swift-facing contract: include/doodleart_core.h (a Swift sample over it: swift/Sources).
//! The JNI natives keep theme-x's shapes (doodleart-core/README.md) until the Android app exists.
//!
//! Platforms: the Android-only parts (`jni` with `JNI_OnLoad`, `apk_identity`, `device_signals`, `sys` and the Android
//! scanners of [`risk`]) are compiled into every build except an Apple library (`cfg(any(not(doodleart_apple_lib),
//! test))`; build.rs sets `doodleart_apple_lib` for iOS and for the macOS slice of build-ios.sh), so a plain macOS build
//! keeps `JNI_OnLoad` for a Kotlin host harness and host `cargo test` covers them. The C ABI (`ffi`) and the Apple scan
//! are compiled into Apple libraries and into the unit tests on a Mac. Everything else is platform-neutral.

